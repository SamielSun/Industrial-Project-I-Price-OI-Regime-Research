def fill_header(doc):
    remaining = dict(HDR)
    for p in doc.paragraphs:
        t = p.text.strip()
        if t in remaining:
            r = p.add_run(" " + remaining.pop(t))
            r.font.size = Pt(12)
    # academic line: placed after the industrial-supervisor line
    if not any(p.text.strip().startswith("Academic Supervisor:") for p in doc.paragraphs):
        for p in doc.paragraphs:
            if p.text.strip().startswith("Industrial Supervisor:"):
                new_el = copy.deepcopy(p._p)
                p._p.addnext(new_el)
                from docx.text.paragraph import Paragraph
                np = Paragraph(new_el, p._parent)
                for r in list(np.runs):
                    r._r.getparent().remove(r._r)
                np.add_run("Academic Supervisor:")
                r = np.add_run(" Prof. WU Xixin")
                r.font.size = Pt(12)
                break
    return remaining


def fill_table(doc):
    t = doc.tables[0]
    template = copy.deepcopy(t.rows[1]._tr)
    while len(t.rows) > 1:
        t._tbl.remove(t.rows[-1]._tr)
    for values in ROWS:
        t._tbl.append(copy.deepcopy(template))
        row = t.rows[-1]
        for cell, value in zip(row.cells, values):
            for extra in cell.paragraphs[1:]:
                extra._p.getparent().remove(extra._p)
            lines = value.split("\n")
            p = cell.paragraphs[0]
            for r in list(p.runs):
                r._r.getparent().remove(r._r)
            p.add_run(lines[0]).font.size = Pt(9)
            for line in lines[1:]:
                np = cell.add_paragraph()
                np.paragraph_format.space_after = Pt(1)
                np.add_run(line).font.size = Pt(9)


