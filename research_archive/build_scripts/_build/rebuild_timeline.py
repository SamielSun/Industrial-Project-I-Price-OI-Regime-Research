"""Rebuild the Proposed Timeline table in FTEC5910_PLAN.docx so that it maps
one-to-one onto the five phases of the execution-plan table.

Agreed constraints:
  * one row per phase, in the same order as the phase table;
  * a biweekly meeting every two weeks, each demonstrating output;
  * all substantive work closes before the end of term (27 Nov 2026);
  * Phase 1 compressed to 6 Oct so that Phase 2 has twelve days before the midterm;
  * the meeting of 6 Nov (M3) accepts Phases 3, 4 and 5 together;
  * four columns only (Dates / Phase / Work / Gate / Demonstration).
"""
import copy
import sys
from docx import Document

PLAN = r"D:\Industrial Programme I\FTEC5910_PLAN.docx"
BACKUP = r"D:\Industrial Programme I\_build\backup_PLAN_before_timeline.docx"

ROWS = [
    ["25 Sep (Fri)", "—",
     "Planning submission: this report and the FinTech Industrial Project Planning Form",
     "Report and Planning Form submitted"],
    ["26 Sep – 6 Oct", "Phase 1 — Data collection",
     "Archive per dataset and symbol, collect hourly OHLCV, open interest, funding rates, volume "
     "and mark/index price if available; verify checksums; build the point-in-time universe ledger "
     "and the coverage matrix by symbol and month.",
     "M1 — biweekly meeting, 9 Oct: demonstrate a verified download, a one-command reproducible "
     "ingest, and the coverage/gap matrix by symbol and month; the measured history depth of the "
     "positioning archive fixes the study start date."],
    ["7 – 18 Oct", "Phase 2 — Regime labelling inputs",
     "Create price/OI regime labels at 1h, 4h and 8h frequencies; align open interest to the price "
     "bar with confidence flags; attach funding to the settlement that charged it; run the threshold "
     "sensitivity table.",
     "M2 — biweekly meeting and midterm submission, 23 Oct: regime counts, frequency by asset and by "
     "market condition, the point-in-time ledger shown to change over time, and the threshold "
     "sensitivity table; D1 and D2 accepted."],
    ["19 Oct – 6 Nov", "Phase 3 — Event study",
     "For each regime, calculate average and median forward return, hit rate, volatility after "
     "event, reversal probability and continuation probability at 1h / 4h / 8h / 24h, plus path "
     "risk (maximum favourable excursion, maximum adverse excursion, drawdown).",
     "M3 — biweekly meeting, 6 Nov: forward-return tables with intervals and observation counts for "
     "every regime, event-study plots and regime comparison charts regenerated by one command."],
    ["19 Oct – 6 Nov", "Phase 4 — Funding interaction",
     "Each regime split by four funding states (low, neutral, high, extreme); 4 × 4 grid of price/OI "
     "regimes against funding states with forward return and volatility by bucket, under the "
     "pre-declared multiplicity correction.",
     "M3 — biweekly meeting, 6 Nov (accepted together with Phase 3): corrected and uncorrected grids "
     "shown side by side, with dependence-robust standard errors."],
    ["7 – 27 Nov", "Phase 5 — Simple strategy test, dashboard and consolidation",
     "Conduct the strategy test only after the event study shows signal value: continuation after "
     "Price Up + OI Up when funding is neutral, and reversal after Price Down + OI Down after "
     "deleveraging, costed against the four baselines; build the dashboard; complete the negative-"
     "result ledger; regenerate every figure and finalise the report.",
     "M4 — biweekly meeting, 20 Nov: dashboard delivered and every figure regenerated by one command, "
     "with the draft report reviewed. M5 — final submission, 27 Nov: all five phases closed and the "
     "final report submitted."],
    ["Week of 30 Nov", "—",
     "End-of-term presentation to the academic and industrial supervisors (30 minutes, including "
     "5 minutes for questions).",
     "—"],
]


def main():
    import shutil
    shutil.copyfile(PLAN, BACKUP)
    print("backup:", BACKUP)

    doc = Document(PLAN)

    # locate the timeline table: the one whose header is Dates / Phase / Work
    idx = None
    for i, t in enumerate(doc.tables):
        header = [c.text.strip().lower() for c in t.rows[0].cells]
        if header[:2] == ["dates", "phase"]:
            idx = i
            break
    if idx is None:
        sys.exit("timeline table not found")

    t = doc.tables[idx]
    template = copy.deepcopy(t.rows[1]._tr)      # keep row formatting

    # clear every row except the header
    for row in list(t.rows[1:]):
        row._tr.getparent().remove(row._tr)

    for values in ROWS:
        t._tbl.append(copy.deepcopy(template))
        row = t.rows[-1]
        for cell, value in zip(row.cells, values):
            for extra in cell.paragraphs[1:]:
                extra._p.getparent().remove(extra._p)
            p = cell.paragraphs[0]
            for r in list(p.runs):
                r._r.getparent().remove(r._r)
            p.add_run(value)

    doc.save(PLAN)
    print(f"rebuilt timeline table ({len(ROWS)} rows) in {PLAN}")

    # ------------------------------------------------------------ verify -----
    d2 = Document(PLAN)
    phases = [r.cells[0].text.strip() for r in d2.tables[1].rows[1:]]
    print("\nphase table rows :", phases)
    print("\ntimeline table   :")
    tt = [t for t in d2.tables if [c.text.strip().lower() for c in t.rows[0].cells][:2]
          == ["dates", "phase"]][0]
    for ri, row in enumerate(tt.rows):
        print(f"  [{ri}] {row.cells[0].text.strip():16s} | {row.cells[1].text.strip()[:44]:46s} | "
              f"{row.cells[2].text.strip()[:56]}")

    timeline_phases = [r.cells[1].text.strip() for r in tt.rows[1:]]
    mapped = [p for p in phases if any(p.split("—")[0].strip() in tp for tp in timeline_phases)]
    print(f"\none-to-one check: {len(mapped)}/{len(phases)} phase-table rows found in the timeline")
    for p in phases:
        key = p.split("—")[0].strip()
        hit = sum(1 for tp in timeline_phases if key in tp)
        print(f"   {key:10s} appears {hit} time(s)")


if __name__ == "__main__":
    main()
